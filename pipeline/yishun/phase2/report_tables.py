"""Phase 2 results tables: docs/phase2/results.md, rebuilt from summary.json so the report never retypes a number.

Usage (from pipeline/):
    python -m yishun.phase2.report_tables [--summary PATH] [--out PATH]

Input:  data/processed/phase2/summary.json (default), written by yishun.phase2.summary.
Output: docs/phase2/results.md: one table per result the report cites, with the provenance of the runs.

Rounding follows the definitions (section 5): costs at two significant figures, passenger-hours to
whole hours (the spread across simulated days is shown beside them), times to 0.1 min.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from ..paths import ROOT
from . import export_web as X

OUT = ROOT / "docs" / "phase2" / "results.md"
KEPT, WITHDRAWN = X.KEPT, X.WITHDRAWN


def _table(head: list[str], rows: list[list], right: set[int] | None = None) -> str:
    right = right if right is not None else set(range(1, len(head)))
    al = ["---:" if j in right else "---" for j in range(len(head))]
    out = ["| " + " | ".join(head) + " |", "| " + " | ".join(al) + " |"]
    out += ["| " + " | ".join("—" if v is None else str(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def _h(x) -> str | None:
    return None if x is None else f"{x:,.0f}"


def _n(x) -> str | None:
    """A mean count of rides: a few rides over several days is "<1", never a misleading 0."""
    return None if x is None else ("<1" if 0 < x < 0.5 else f"{x:,.0f}")


GROUP_NAMES = {"hub": "station or estate", "band": "ride distance", "subzone": "subzone of origin"}


def _min(x) -> str | None:
    return None if x is None else f"{x:.1f}"


def _pct(x, nd=0) -> str | None:
    return None if x is None else f"{100 * x:.{nd}f}%"


def _cost_row(S: dict, i: str, mode: str, case: str, bus_case: str = KEPT) -> dict | None:
    return next((r for r in S["costs"] if r["id"] == i and r["staff_mode"] == mode and r["case"] == case
                 and r["bus_case"] == bus_case), None)


def build(S: dict) -> str:
    P = X.build(S)
    cfg_s = {c["id"]: c for c in S["configs"]}
    cfg = {c["id"]: c for c in P["configs"]}
    refs = [i for i in [P["refs"]["B"], *P["refs"]["C"]] if i]
    modes = P["modes"]
    lab = lambda i: "A: today's buses" if i == "A" else cfg[i]["label"]
    pv = S["provenance"]
    L = ["# Phase 2 results tables", "",
         "Generated by `python -m yishun.phase2.report_tables` from `data/processed/phase2/summary.json`; do not edit by hand.",
         f"Summary built at commit `{pv.get('git')}` (tracked pipeline files modified: {pv.get('pipeline_modified')}); "
         f"model key `{pv.get('model_key')}`, demand months {', '.join(pv.get('demand_months', []))}, "
         f"seeds {', '.join(map(str, pv.get('seeds', [])))}. Cost parameters: `{pv.get('cost_parameters')}` "
         f"(sha256 `{(pv.get('cost_parameters_sha256') or '')[:12]}…`). {P['units']}.", "",
         _table(["Grid", "Runs", "Commit", "Tracked pipeline files modified", "Model key"],
                [[g, v["runs"], f"`{v['git']}`", v["pipeline_modified"], f"`{v['model_key']}`"]
                 for g, v in pv.get("grid_runs", {}).items()], right={1}), ""]

    # 1 service and passenger time
    L += ["## 1. Reference configurations: service and passenger time", "",
          "Means over the simulated weekdays (the spread across days in brackets: random variation between simulated "
          "days, nothing more). Stop-to-stop times; declined rides take the bus at today's time (treatment R1).", ""]
    rows = []
    for i in ["A", *refs]:
        c, cs = cfg[i], cfg_s[i]
        if i == "A":
            rows.append([lab(i), _h(c["n"]), "—", "—", "—", _h(c["pax_h_A"]), _h(cs.get("wait_h_A")), _h(cs.get("ivt_h_A")), "—",
                         _min(c["mean_min_A"]), _min(c["p90_min_A"]), str(c["n_seeds"])])
            continue
        rows.append([lab(i), _h(c["n"]), f"{_h(c['n_shuttle'])} ({_pct(c['n_shuttle'] / c['n'])})", _n(c["n_declined"]),
                     _n(c["n_refused"]), _h(c["pax_h"]), _h(cs.get("wait_h")), _h(cs.get("ivt_h")),
                     f"{_h(c['saved_h'])} ({_h(c['saved_h_min'])}–{_h(c['saved_h_max'])})",
                     _min(c["mean_min"]), _min(c["p90_min"]), str(c["n_seeds"])])
    L += [_table(["Configuration", "Rides", "By shuttle", "Declined", "Refused", "Passenger-h", "of which waiting",
                  "in vehicle", "Saved passenger-h (days)", "Mean min", "p90 min", "Days"], rows, right={1, 3, 4, 5, 6, 7, 9, 10, 11}), ""]

    # 2 resources
    L += ["## 2. Reference configurations: vehicles and resources", "",
          "Simulated vehicle use per weekday. Total fleet = vehicles in service plus the estimated charging and "
          "maintenance reserves (an estimate, not a charging simulation). Kerb: most shuttles boarding or alighting at "
          "once at the station stops (mean over days of the daily maximum).", ""]
    rows = []
    det0 = P["cost_detail"][modes[0]]
    for i in refs:
        c, cs, d = cfg[i], cfg_s[i], det0.get(i, {})
        rows.append([lab(i), _h(cs.get("fleet_in_service")), _h(d.get("total_fleet")), _h(d.get("charging_reserve")),
                     _h(d.get("maintenance_reserve")), _h(cs.get("veh_hours_in_service")), _h(cs.get("moving_h")), _h(cs.get("veh_km")),
                     f"{_h(cs.get('veh_km_empty'))} ({_pct(cs['veh_km_empty'] / cs['veh_km'])})" if cs.get("veh_km") else None,
                     f"{cs.get('occupancy', 0):.2f}" if cs.get("occupancy") else None, _h(d.get("unavailable_vehicle_hours")),
                     f"{cs.get('kerb_max_Yishun', 0):.0f} / {cs.get('kerb_max_Khatib', 0):.0f}"])
    sup = S["bus"]["supply"]
    L += [_table(["Configuration", "In service", "Total fleet (est.)", "Charging reserve", "Maintenance reserve", "Vehicle-h in service",
                  "Vehicle-h moving", "Vehicle-km", "Empty km", "Riders on board", "Unavailable vehicle-h", "Kerb Yishun / Khatib"], rows), "",
          f"Buses for comparison (modelled from published headways): {_h(sup['all_bus_km'])} bus-km and {_h(sup['all_bus_hours'])} "
          f"bus-hours a weekday inside Yishun for all services, about {_h(sup['all_buses_07'])} buses in the area at 07:00; the "
          f"{S['bus']['allocation'].get('internal_only_services') and len(S['bus']['allocation']['internal_only_services'])} "
          f"services that carry only internal riders run {_h(sup['bus_km'])} bus-km and {_h(sup['bus_hours'])} bus-hours "
          f"(about {_h(sup['buses_07'])} buses at 07:00).", ""]

    # 3 costs
    L += ["## 3. Daily cost and cost per passenger-hour saved, by staffing case", "",
          "Additional operating cost against Option A with all buses kept; central case and the low-to-high cost cases. "
          "B (ii) withdraws the services that carry only internal riders (a theoretical bound, not a plan). Its avoided bus "
          "cost is shown at the full resource cost per bus-km (operator fee plus LTA's bus and depot capital) and at the "
          "operator fee only, since the fee includes a lease charge for LTA's assets that may already recover part of that "
          "capital. Time savings are not operator revenue.", ""]
    for m in modes:
        L += [f"### {P['staff_modes'][m]['label'][:1].upper()}{P['staff_modes'][m]['label'][1:]}", ""]
        rows = []
        for i in refs:
            e = P["costs"][m][i]
            r = _cost_row(S, i, m, "central")
            row = [lab(i), X.sgd(e["shuttle_cost"]["central"]), X.sgd_range(e["delta_cost"]["low"], e["delta_cost"]["high"]),
                   X.sgd(e["cost_per_hour_saved"]["central"]),
                   X.sgd_range(e["cost_per_hour_saved"]["low"], e["cost_per_hour_saved"]["high"]),
                   X.sgd(r["cost_per_shuttle_ride"]), X.sgd(r["cost_per_shuttle_pax_km"]),
                   f"{_pct(r['share_staff'])} / {_pct(r['share_fixed'])} / {_pct(r['share_distance'])}", e["classification"]["central"]]
            rows.append(row)
            for side, what in (("withdrawn", "full bus cost"), ("withdrawn_fee", "operator fee only")):
                w = e.get(side)
                if w:
                    rows.append([f"{lab(i)}, (ii) internal-only services withdrawn, {what} avoided "
                                 f"({X.sgd(w['avoided_bus_cost']['central'])} a day)", X.sgd(w["delta_cost"]["central"]),
                                 X.sgd_range(w["delta_cost"]["low"], w["delta_cost"]["high"]), X.sgd(w["cost_per_hour_saved"]["central"]),
                                 X.sgd_range(w["cost_per_hour_saved"]["low"], w["cost_per_hour_saved"]["high"]), None, None, None,
                                 w["classification"]["central"]])
        L += [_table(["Configuration", "Added cost (central)", "Added cost (low–high)", "Per passenger-h saved (central)",
                      "Per passenger-h saved (low–high)", "Per shuttle ride", "Per shuttle passenger-km", "Staff / fixed / distance",
                      "Classification (central)"], rows, right={1, 2, 3, 4, 5, 6}), ""]
    n_cls = {m: {k: sum(1 for i, e in P["costs"][m].items() if cfg.get(i, {}).get("acceptable") and e["classification"]["central"] == k)
                 for k in X.CLASSES} for m in modes}
    L += ["Classification of every configuration with acceptable service (central case, all buses kept):", "",
          _table(["Staffing", *X.CLASSES], [[P["staff_modes"][m]["short"], *[n_cls[m][k] for k in X.CLASSES]] for m in modes]), ""]

    # 4 refused and declined rides
    L += ["## 4. Declined and refused rides: treatments", "",
          "R1 (default): a declined ride takes the bus at today's time. R2: each refused or declined ride costs 45 minutes plus "
          "a direct ride (a penalty, B's refusals always use it). R3: a declined ride waits 5 minutes before taking the bus.", ""]
    rows = []
    for i in refs:
        c = cfg[i]
        cr = [_cost_row(S, i, m, "central") for m in modes]
        rows.append([lab(i), _n(c["n_declined"]), _n(c["n_refused"]), _h(c["saved_h"]), _h(c["saved_h_R2"]), _h(c["saved_h_R3"]),
                     " / ".join(X.sgd(r["cost_per_hour_saved_R2"]) or "—" for r in cr)])
    L += [_table(["Configuration", "Declined", "Refused", "Saved passenger-h R1", "R2", "R3",
                  "Per passenger-h saved under R2 (" + " / ".join(P["staff_modes"][m]["short"] for m in modes) + ")"], rows), ""]

    # 5 by period
    L += ["## 5. Who gains: passenger-hours saved by period", "",
          "Sums over the rides requested in each period (not averages of means); mean times use the expected bus time. "
          "Faster/slower: shares of all rides in the period that reach their stop sooner or later than the same ride by "
          "bus, with one simulated bus wait per ride (as in Phase 1); rides that stay on the bus are neither.", ""]
    rows = []
    for i in refs:
        for r in S["who"][i]["period"]:
            rows.append([lab(i), f"{X.PERIOD_NAMES.get(r['period'], r['period'])} {r['label']}", _h(r["n"]),
                         _pct(r.get("offered_share")), _h(r["saved_h"]), _pct(r.get("saved_share")),
                         f"{_min(r['mean_min_A'])} → {_min(r['mean_min'])}", _pct(r.get("faster_share")), _pct(r.get("slower_share"), 1)])
    L += [_table(["Configuration", "Period", "Rides", "Offered a shuttle", "Saved passenger-h", "Saved share", "Mean min (A → option)",
                  "Faster", "Slower"], rows, right={2, 3, 4, 5, 6, 7, 8}), ""]
    groups = [k for k in S["who"][refs[0]] if k != "period"]
    for gk in groups:
        rows = []
        for i in refs:
            for r in S["who"][i].get(gk, []):
                rows.append([lab(i), r.get("label") or str(r.get(gk, r.get("group", ""))), _h(r["n"]), _h(r["saved_h"]), _pct(r.get("saved_share")),
                             f"{_min(r['mean_min_A'])} → {_min(r['mean_min'])}", _pct(r.get("faster_share")), _pct(r.get("slower_share"), 1)])
        if rows:
            L += [f"By {GROUP_NAMES.get(gk, gk.replace('_', ' '))}:", "",
                  _table(["Configuration", GROUP_NAMES.get(gk, gk.replace("_", " ")).capitalize(), "Rides", "Saved passenger-h", "Saved share", "Mean min (A → option)",
                          "Faster", "Slower"], rows, right={2, 3, 4, 5, 6, 7}), ""]

    # 6 budgets
    L += ["## 6. What a budget buys", "",
          "The most passenger-hours saved per weekday by any configuration with acceptable service whose additional cost "
          "(all buses kept) is within the budget, per cost case.", ""]
    for m in modes:
        rows = []
        for r in P["budgets"][m]:
            cells = [X.sgd(r["budget"])]
            for case in X.CASES:
                b = r.get(case)
                cells.append(None if not b else f"{cfg[b['id']]['short']}: {_h(b['saved_h'])} h at {X.sgd(b['cost_per_hour_saved'])}/h")
            rows.append(cells)
        L += [f"*{P['staff_modes'][m]['short']}*", "", _table(["Budget per weekday", "Low-cost case", "Central case", "High-cost case"],
                                                              rows, right={0}), ""]

    # 7 thresholds
    L += ["## 7. Thresholds (central case)", "",
          "Each value is where a stated target is met; whether it is achievable or permitted is a separate question. "
          "'Value-of-time budget': the daily cost at which cost per passenger-hour saved equals the central value of "
          "in-vehicle time (a social benchmark, not revenue).", ""]
    for m in modes:
        rows = []
        for i in refs:
            t = P["thresholds"][m].get(i)
            if not t:
                continue
            rph = {x["target"]: x for x in t["rides_per_vehicle_hour"]}
            fare = next((x for k, x in rph.items() if "fare" in k), None)
            be = [(k[len("break_even_"):], v) for k, v in t.items() if k.startswith("break_even_") and isinstance(v, dict)]
            be_txt = "; ".join(f"{X.PARAM_LABELS.get(k, k)} {X._num(v['value'], 2) if v.get('value') is not None else 'not met'} "
                               f"(central {X._num(v['central'], 3) if v.get('central') is not None else '—'})" for k, v in be)
            mc = [x for x in t["budget_max_cost_per_vehicle_day"]]
            mc_txt = ", ".join(f"{X.sgd(x['budget'])}: {X.sgd(x['value'])}" for x in mc[:6])
            rows.append([lab(i), X.sgd(t.get("break_even_daily_cost")), be_txt or "—",
                         f"{fare['value']:.1f} (now {fare['current']:.1f})" if fare and fare.get("value") else (f"not met (now {fare['current']:.1f})" if fare else "—"),
                         f"{X.sgd(mc[0]['current'])}" if mc else "—", mc_txt])
        L += [f"*{P['staff_modes'][m]['short']}*", "",
              _table(["Configuration", "Value-of-time budget per day", "Parameter value at that budget (break-even)",
                      "Rides per vehicle-hour for SGD 4 a ride", "Cost per vehicle-day now", "Most cost per vehicle-day within a budget"],
                     rows, right={1, 3, 4}), ""]

    # 8 stress
    L += ["## 8. Stress tests", "",
          "Passenger-hours saved against Option A in the same conditions (mean of the simulated days), declined and refused "
          "rides. Speed stresses scale road times for buses and shuttles alike; added shuttle traffic slows nothing, because "
          "congestion is not modelled.", ""]
    st = P["stress"]
    ids = list(dict.fromkeys([*refs, *[r["id"] for r in st]]))
    rows = [["Base case", *[_h(cfg[i]["saved_h"]) if i in cfg else "—" for i in ids]]]
    for k in P["stress_labels"]:
        cells = [k]
        for i in ids:
            r = next((x for x in st if x["stress"] == k and x["id"] == i), None)
            if not r:
                cells.append("—")
                continue
            note = f" ({_h(r['refused'])} refused)" if r["refused"] else (f" ({_h(r['declined'])} declined)" if r["declined"] else "")
            cells.append(f"{_h(r['saved_h'])}{note}")
        rows.append(cells)
    L += [_table(["Condition", *[cfg[i]["short"] if i in cfg else i for i in ids]], rows), ""]
    if any(r.get("saved_h_R2") is not None for r in st):
        rows = []
        for k in P["stress_labels"]:
            cells = [k]
            for i in ids:
                r = next((x for x in st if x["stress"] == k and x["id"] == i), None)
                cells.append("—" if not r or r.get("saved_h_R2") is None else
                             f"{_h(r['saved_h_R2'])} / {_h(r['saved_h_R3'])}" if r["declined"] or r["refused"] else "as R1")
            rows.append(cells)
        L += ["The same stresses under the other treatments of declined and refused rides (R2 / R3):", "",
              _table(["Condition", *[cfg[i]["short"] if i in cfg else i for i in ids]], rows), ""]

    # 9 bus model error
    L += ["## 9. If the bus model overstates bus times on the rides the shuttle takes", "",
          "C selects rides by their modelled bus time, so an overstatement there inflates C's saving. Saving if the modelled "
          "bus time of the rides the shuttle carried were too high by 10, 20 or 30 %.", ""]
    rows = [[lab(r["id"]), _h(r["saved_h"]), _h(r["shuttle_rides_bus_hours"]), _h(r.get("saved_h_e10")), _h(r.get("saved_h_e20")),
             _h(r.get("saved_h_e30"))] for r in P["bus_error"]]
    L += [_table(["Configuration", "Saved passenger-h", "Bus passenger-h of the shuttle's rides", "−10 %", "−20 %", "−30 %"], rows), ""]

    # 10 bus cost and allocation
    b = P["bus"]
    al = S["bus"]["allocation"]
    L += ["## 10. Bus cost inside Yishun and its allocation", "",
          f"Internal riders account for {_pct(b['internal_share'], 1)} of the bus passenger-km inside Yishun "
          f"({_pct(al['ride_share']['internal'], 1)} of the rides that use its buses); the rest are riders entering, leaving or passing "
          f"through. Months {', '.join(al['months'])}; {al['method']}.", ""]
    rows = [[case, X.sgd(b["cost"][case]["all"]), X.sgd(b["cost"][case]["allocated_internal"]),
             X.sgd(b["cost"][case]["allocated_internal_by_rides"]), X.sgd(b["cost"][case]["avoidable_internal_only"])] for case in X.CASES]
    L += [_table(["Cost case", "All buses in the area", "Allocated to internal riders (passenger-km)", "Allocated by rides (check)",
                  "Avoidable bound: internal-only services"], rows), ""]

    # 11 social
    L += ["## 11. Separate social estimate: value of the time saved", "",
          "Not operator revenue and not part of the cost comparison. In-vehicle hours saved plus a waiting weight times waiting "
          "hours saved, at a value of in-vehicle time (low, central and high values together).", ""]
    rows = []
    for i in refs:
        s = P["social"].get(i)
        if not s:
            continue
        for case in X.CASES:
            v = s[case]
            rows.append([lab(i), case, f"SGD {v['vot']:g}/h × wait {v['wait_weight']:g}", X.sgd(v["benefit_sgd_per_day"]),
                         " / ".join(f"{v.get(f'benefit_cost_ratio_{m}'):.2f}" if v.get(f"benefit_cost_ratio_{m}") is not None else "—" for m in modes)])
    L += [_table(["Configuration", "Values", "Value of time and weight", "Value per weekday",
                  "Value ÷ added cost (" + " / ".join(P["staff_modes"][m]["short"] for m in modes) + ")"], rows, right={3, 4}), ""]

    # 12 service-level fleets
    L += ["## 12. Service-level fleets", "",
          "The smallest simulated fleet with acceptable service: at most 1 % of offered rides declined in every hour of every "
          "simulated day, and no refusals, with every larger simulated fleet also passing (base scenario).", ""]
    rows = []
    for r in S["service_level"]:
        if r["scenario"] != "base" or r["availability"] != 1.0 or r["berths"] != -1:
            continue
        t = r["theta_min"]
        hours = "all day"
        if r["hours"]:
            a, b = (int(x) for x in str(r["hours"]).split("-"))
            hours = f"{a % 24:02d}:00–{(b + 1) % 24:02d}:00"
        rows.append(["every ride" if t is None or t <= X.ALL_RIDES else f"θ {X.theta_txt(t)}", r["capacity"], hours, f"{r['w_max_s'] / 60:g} min", ("none simulated" if r["fleet_sl"] is None else
                      f"≤ {int(r['fleet_sl'])} (smallest simulated)" if r["fleet_sl"] == min(r["fleets"]) else int(r["fleet_sl"])),
                     ", ".join(str(int(f)) for f in r["fleets"]), "yes" if r["monotone"] else "no"])
    L += [_table(["Coverage", "Seats", "Hours", "Decline limit", "Service-level fleet", "Fleets simulated", "Monotone"], rows,
                 right={1, 4}), ""]

    # 13 every B configuration and the C variants
    L += ["## 13. B fleets and C variants", "",
          "Every simulated B fleet and every C variant (other vehicle sizes, the 45-minute decline limit, service after "
          "20:00 only), base scenario. Added cost and cost per passenger-hour saved: central case, all buses kept, per "
          "staffing case (" + " / ".join(P["staff_modes"][m]["short"] for m in modes) + ").", ""]
    rows = []
    for c in P["configs"]:
        if c["option"] == "A" or c["kind"] == "C":
            continue
        e = [P["costs"][m].get(c["id"]) for m in modes]
        rows.append([c["label"], "yes" if c["acceptable"] else "no", _h(c["saved_h"]), _h(c["n_declined"]), _h(c["n_refused"]),
                     " / ".join(X.sgd(x["delta_cost"]["central"]) if x else "—" for x in e),
                     " / ".join((X.sgd(x["cost_per_hour_saved"]["central"]) or "—") if x else "—" for x in e)])
    L += [_table(["Configuration", "Acceptable service", "Saved passenger-h", "Declined", "Refused", "Added cost", "Per passenger-h saved"],
                 rows, right={2, 3, 4}), ""]
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--summary", type=Path, default=X.SUMMARY)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    text = build(json.loads(Path(a.summary).read_text()))
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(text)
    print(f"wrote {a.out} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
